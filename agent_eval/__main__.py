"""Allow running as: python -m agent_eval <command>

Subcommands: config, state.
Skills handle orchestration: /eval-setup, /eval-analyze, /eval-run, /eval-mlflow, /eval-optimize.
"""

import sys


def main():
    if len(sys.argv) < 2:
        print("Usage: python -m agent_eval <config|state>", file=sys.stderr)
        print("  config   validate|check-eval-md|write-eval-md")
        print("  state    init|set|read|write-ids|read-ids|clean|timestamp")
        sys.exit(1)

    command = sys.argv[1]

    if command == "config":
        sys.argv = sys.argv[1:]
        _config_command()
    elif command == "state":
        sys.argv = sys.argv[1:]
        from .state import main as state_main
        state_main()
    else:
        print(f"Unknown command: {command}", file=sys.stderr)
        print("Available: config, state", file=sys.stderr)
        sys.exit(1)


def _config_command():
    if len(sys.argv) < 2:
        print("Usage: python -m agent_eval config <validate|check-eval-md|write-eval-md>")
        sys.exit(1)

    subcmd = sys.argv[1]

    if subcmd == "validate":
        path = sys.argv[2] if len(sys.argv) > 2 else "eval.yaml"
        from .config import EvalConfig
        try:
            config = EvalConfig.from_yaml(path)
            print(f"Valid: {config.name} (skill={config.skill})")
        except Exception as e:
            print(f"Invalid: {e}", file=sys.stderr)
            sys.exit(1)

    elif subcmd == "check-eval-md":
        path = sys.argv[2] if len(sys.argv) > 2 else "eval.md"
        _check_eval_md(path)

    elif subcmd == "write-eval-md":
        import argparse
        parser = argparse.ArgumentParser()
        parser.add_argument("path")
        parser.add_argument("--skill", required=True)
        parser.add_argument("--data", required=True)
        args = parser.parse_args(sys.argv[2:])
        _write_eval_md(args.path, args.skill, args.data)

    else:
        print(f"Unknown config subcommand: {subcmd}", file=sys.stderr)
        sys.exit(1)


def _check_eval_md(path):
    import hashlib
    from pathlib import Path
    import yaml

    p = Path(path)
    if not p.exists():
        print("STALE: eval.md does not exist")
        sys.exit(1)

    content = p.read_text()
    if not content.startswith("---"):
        print("STALE: no frontmatter")
        sys.exit(1)

    parts = content.split("---", 2)
    if len(parts) < 3:
        print("STALE: invalid frontmatter")
        sys.exit(1)

    fm = yaml.safe_load(parts[1])
    if not fm:
        print("STALE: empty frontmatter")
        sys.exit(1)

    skill_name = fm.get("skill", "")
    stored_hash = fm.get("skill_hash", "")

    for skills_dir in [Path(".claude/skills"), Path("skills")]:
        skill_path = skills_dir / skill_name / "SKILL.md"
        if skill_path.exists():
            current_hash = hashlib.sha256(skill_path.read_bytes()).hexdigest()[:12]
            if current_hash == stored_hash:
                print("FRESH")
                return
            else:
                print(f"STALE: hash mismatch ({stored_hash} != {current_hash})")
                sys.exit(1)

    print(f"STALE: skill {skill_name} not found")
    sys.exit(1)


def _write_eval_md(path, skill, data_yaml):
    import hashlib
    from datetime import datetime, timezone
    from pathlib import Path
    import yaml

    data = yaml.safe_load(data_yaml)

    skill_hash = ""
    for skills_dir in [Path(".claude/skills"), Path("skills")]:
        skill_path = skills_dir / skill / "SKILL.md"
        if skill_path.exists():
            skill_hash = hashlib.sha256(skill_path.read_bytes()).hexdigest()[:12]
            break

    fm = {
        "skill": skill,
        "analyzed_at": datetime.now(timezone.utc).isoformat(),
        "skill_hash": skill_hash,
    }
    fm.update(data.get("frontmatter", data))
    fm_str = yaml.dump(fm, default_flow_style=False, allow_unicode=True)

    body = data.get("body", f"# Evaluation Context: {skill}\n\nAuto-generated by /eval-analyze.\n")
    Path(path).write_text(f"---\n{fm_str}---\n\n{body}\n")
    print(f"Written: {path}")


if __name__ == "__main__":
    main()
